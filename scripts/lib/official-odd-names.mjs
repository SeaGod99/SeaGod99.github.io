// official-odd-names.mjs — 「看起來不像台服名」的台服官方名稱特例
//
// scripts/lib/tw-text.mjs 的 isTw() 是全站的台服名守門：要求含漢字、擋掉以 ● ※ × 開頭的內部佔位
// （「●未使用アクション」那種）。這兩條規則本身是對的，**不要為了特例放寬**。
// 但遊戲裡確實有幾個正式名稱剛好撞到規則——擋掉的話，該顯示的東西會安靜消失。
// 這裡逐筆列出（種類 → id → 理由），用到的建置腳本要以 id 判斷，不要以名稱判斷。
//
// 加之前先對台服客戶端與 Teamcraft 台服語系檔確認兩邊都是同一個名字，並寫下理由。

export const ODD_NAMES = {
  quest: new Map([
    // 2026-10-10：主線頁一直少這兩筆，曉月之終途第 11 章的前置鏈在這裡斷了兩處（69991→69992→69993、69996→69997→69998）
    [69992, "曉月之終途主線（極北之地）：任務名刻意用 ● 遮字（同章還有「萬■皆陳腐」「捨棄●●的漫長歲月」），剛好以 ● 開頭，被當成內部佔位"],
    [69997, "曉月之終途主線：台服官方任務名就是英文「Hello, World」，不含漢字"],
  ]),
};

/** 這個名字是不是列在特例裡的官方名（種類＋id 都要對上） */
export function isOddOfficial(kind, id) {
  return !!ODD_NAMES[kind]?.has(Number(id));
}
